"""PDDL 2.1 writer (domain + problem with timed initial literals and deadline encoding) and the
round-trip check that reads the generated PDDL back and compares it with the source.
"""

"""This file is UN-VERIFIED"""


import os
import re
from collections import OrderedDict

from .domain_spec import Atom, TIME_POINTS_COND, TIME_POINTS_EFF


# ==================== Writer =====================================================================
_PT_PDDL = {"at_start": "at start", "over_all": "over all", "at_end": "at end"}


def fmt_num(v) -> str:
    if isinstance(v, bool):
        raise TypeError("boolean is not a number")
    if float(v).is_integer():
        return str(int(v))
    return repr(round(float(v), 6))


def _atom(a: Atom) -> str:
    body = "({})".format(" ".join((a.pred,) + a.args))
    return "(not {})".format(body) if a.negated else body


def _fact(f) -> str:
    return "({})".format(" ".join(f))


def _typed(params) -> str:
    return " ".join("{} - {}".format(p.name, p.type) for p in params)


def _grouped(names_types):
    by = OrderedDict()
    for n, t in names_types:
        by.setdefault(t, []).append(n)
    return by


# ---- domain --------------------------------------------------------------------------
def write_domain(spec) -> str:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = [";; Generated by pddl_generator from {}".format(
        ", ".join(os.path.relpath(f, root) for f in spec.source_files)),
           ";; spec sha256 {}".format(spec.sha256()),
           "(define (domain {})".format(spec.name),
           "  (:requirements {})".format(" ".join(spec.requirements))]
    # types: children grouped under their parent
    children = _grouped(sorted((t, p) for t, p in spec.types.items() if t != "object"))
    out.append("  (:types\n    {})".format("\n    ".join(
        "{} - {}".format(" ".join(sorted(ts)), parent) for parent, ts in children.items())))
    if spec.constants:
        consts = _grouped(sorted((c, t) for c, t in spec.constants.items()))
        out.append("  (:constants {})".format(" ".join(
            "{} - {}".format(" ".join(cs), t) for t, cs in consts.items())))
    out.append("  (:predicates\n    {})".format("\n    ".join(
        "({} {})".format(p, _typed(sig)).replace(" )", ")") for p, sig in spec.predicates.items())))
    if spec.functions:
        out.append("  (:functions\n    {})".format("\n    ".join(
            "({} {})".format(f, _typed(sig)).replace(" )", ")") for f, sig in spec.functions.items())))
    for act in spec.actions.values():
        if isinstance(act.duration, Atom):
            dur = "(= ?duration {})".format(_atom(act.duration))
        else:
            dur = "(= ?duration {})".format(fmt_num(act.duration))
        conds = ["({} {})".format(_PT_PDDL[pt], _atom(a)) for pt in TIME_POINTS_COND for a in act.conditions[pt]]
        effs = ["({} {})".format(_PT_PDDL[pt], _atom(a)) for pt in TIME_POINTS_EFF for a in act.effects[pt]]
        out.append("\n  (:durative-action {}\n    :parameters ({})\n    :duration {}\n"
                   "    :condition (and\n      {})\n    :effect (and\n      {}))".format(
                       act.name, _typed(act.params), dur, "\n      ".join(conds), "\n      ".join(effs)))
    out.append(")")
    return "\n".join(out) + "\n"


# ---- problem -------------------------------------------------------------------------
def deadline_literals(spec, problem):
    """[(time, window_fact)] timed literals that close each deadlined goal's window."""
    enc = spec.deadline_encoding or {}
    out = []
    for g in problem.goals:
        if g.deadline is None:
            continue
        window = (enc["window_predicate"],) + tuple(g.fact[1:])
        if window not in set(problem.facts):
            raise ValueError("deadline on {} needs {} in the initial state".format(g.fact, window))
        out.append((float(g.deadline) + float(enc.get("til_offset", 0.0)), window))
    return out


def write_problem(spec, problem) -> str:
    problem.validate(spec)
    objs = _grouped(sorted((o.name, o.type) for o in problem.objects))
    init = [_fact(f) for f in sorted(problem.facts)]
    init += ["(= ({}) {})".format(" ".join(k), fmt_num(v)) for k, v in sorted(problem.fluents.items())]
    tils = [(t.time, ("{}" if t.value else "(not {})").format(_fact(t.fact))) for t in problem.timed_literals]
    tils += [(t, "(not {})".format(_fact(w))) for t, w in deadline_literals(spec, problem)]
    init += ["(at {} {})".format(fmt_num(t), lit) for t, lit in sorted(tils)]
    goal = " ".join(_fact(g.fact) for g in problem.goals)
    metric = {"makespan": "(:metric minimize (total-time))"}[problem.metric]
    return ("(define (problem {name}) (:domain {dom})\n"
            "  (:objects\n    {objs})\n"
            "  (:init\n    {init})\n"
            "  (:goal (and {goal}))\n"
            "  {metric})\n").format(
        name=problem.instance_id, dom=spec.name,
        objs="\n    ".join("{} - {}".format(" ".join(ns), t) for t, ns in objs.items()),
        init="\n    ".join(init), goal=goal, metric=metric)


# ==================== Round-trip check ===========================================================
def tokenize(text):
    text = re.sub(r";[^\n]*", "", text)
    return re.findall(r"\(|\)|[^\s()]+", text.lower())


def parse_sexpr(text):
    toks = tokenize(text)
    stack, cur = [], []
    for t in toks:
        if t == "(":
            stack.append(cur)
            cur = []
        elif t == ")":
            done, cur = cur, stack.pop()
            cur.append(done)
        else:
            cur.append(t)
    if stack:
        raise ValueError("unbalanced parentheses")
    if len(cur) != 1:
        raise ValueError("expected one top-level expression, got {}".format(len(cur)))
    return cur[0]


def _sections(expr):
    return {e[0]: e for e in expr[2:] if isinstance(e, list) and e and isinstance(e[0], str)}


def _num(x):
    v = float(x)
    return int(v) if v.is_integer() else v


def read_problem(text):
    e = parse_sexpr(text)
    sec = _sections(e)
    objects, pending = {}, []
    toks = sec[":objects"][1:]
    i = 0
    while i < len(toks):
        if toks[i] == "-":
            for n in pending:
                objects[n] = toks[i + 1]
            pending, i = [], i + 2
        else:
            pending.append(toks[i])
            i += 1
    facts, fluents, tils = set(), {}, set()
    for item in sec[":init"][1:]:
        if item[0] == "=":
            fluents[tuple(item[1])] = _num(item[2])
        elif item[0] == "at" and len(item) == 3 and not isinstance(item[1], list) \
                and re.fullmatch(r"[0-9.]+", item[1]):
            lit = item[2]
            if lit[0] == "not":
                tils.add((float(item[1]), tuple(lit[1]), False))
            else:
                tils.add((float(item[1]), tuple(lit), True))
        else:
            facts.add(tuple(item))
    g = sec[":goal"][1]
    goals = [tuple(x) for x in g[1:]] if g[0] == "and" else [tuple(g)]
    return {"name": e[1][1], "domain": sec[":domain"][1], "objects": objects, "facts": facts,
            "fluents": fluents, "tils": tils, "goals": goals, "metric": sec.get(":metric")}


def read_domain(text):
    e = parse_sexpr(text)
    actions = {}
    for item in e[2:]:
        if item[0] != ":durative-action":
            continue
        name, kv = item[1], {}
        for k in range(2, len(item), 2):
            kv[item[k]] = item[k + 1]
        params = [t for t in kv[":parameters"] if t.startswith("?")]
        dur = kv[":duration"][2]
        conds = {"at start": set(), "over all": set(), "at end": set()}
        for c in kv[":condition"][1:]:
            conds[c[0] + " " + c[1]].add(_lit(c[2]))
        effs = {"at start": set(), "at end": set()}
        for c in kv[":effect"][1:]:
            effs[c[0] + " " + c[1]].add(_lit(c[2]))
        actions[name] = {"params": params, "duration": tuple(dur) if isinstance(dur, list) else _num(dur),
                         "conditions": conds, "effects": effs}
    return {"name": e[1][1], "actions": actions}


def _lit(x):
    return ("not",) + tuple(x[1]) if x[0] == "not" else tuple(x)


# ---- comparisons -----------------------------------------------------------------------
def check_problem_roundtrip(spec, problem, pddl_text):
    """Return a list of discrepancies (empty = exact round trip)."""
    r = read_problem(pddl_text)
    errs = []
    want_objs = {o.name: o.type for o in problem.objects}
    if r["objects"] != want_objs:
        errs.append("objects differ: {}".format(set(r["objects"].items()) ^ set(want_objs.items())))
    if r["facts"] != set(problem.facts):
        errs.append("init facts differ: {}".format(r["facts"] ^ set(problem.facts)))
    want_fl = {k: v for k, v in problem.fluents.items()}
    if r["fluents"] != want_fl:
        errs.append("fluents differ: {}".format(set(r["fluents"].items()) ^ set(want_fl.items())))
    want_tils = {(float(t.time), tuple(t.fact), t.value) for t in problem.timed_literals}
    want_tils |= {(t, w, False) for t, w in deadline_literals(spec, problem)}
    if r["tils"] != want_tils:
        errs.append("timed literals differ: {}".format(r["tils"] ^ want_tils))
    if r["goals"] != [tuple(g.fact) for g in problem.goals]:
        errs.append("goals differ")
    if r["domain"] != spec.name or r["name"] != problem.instance_id.lower():
        errs.append("header differs")
    return errs


def check_domain_roundtrip(spec, pddl_text):
    r = read_domain(pddl_text)
    errs = []
    if set(r["actions"]) != set(spec.actions):
        errs.append("action names differ: {}".format(set(r["actions"]) ^ set(spec.actions)))
    for name, act in spec.actions.items():
        got = r["actions"].get(name)
        if got is None:
            continue
        if got["params"] != act.param_names:
            errs.append("{}: parameters differ".format(name))
        want_dur = (act.duration.pred,) + act.duration.args if hasattr(act.duration, "pred") else act.duration
        if got["duration"] != want_dur:
            errs.append("{}: duration differs".format(name))
        for pt, key in (("at_start", "at start"), ("over_all", "over all"), ("at_end", "at end")):
            want = {(("not",) if a.negated else ()) + (a.pred,) + a.args for a in act.conditions[pt]}
            if got["conditions"][key] != want:
                errs.append("{}: {} conditions differ".format(name, key))
        for pt, key in (("at_start", "at start"), ("at_end", "at end")):
            want = {(("not",) if a.negated else ()) + (a.pred,) + a.args for a in act.effects[pt]}
            if got["effects"][key] != want:
                errs.append("{}: {} effects differ".format(name, key))
    return errs
